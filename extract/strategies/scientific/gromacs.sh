#!/bin/bash
## Name: gromacs
## Description: Extract performance and data from GROMACS .xvg and .log output
## Version: 1.0
## Priority: 10
## Sample: samples/gromacs/basic.txt

strategy_detect () {
    local text="$1"
    _STRATEGY_CONFIDENCE=0

    local hits=0
    [[ "$text" == *"GROMACS"* ]] && hits=$((hits + 1))
    [[ "$text" == *"gmx"* ]] && hits=$((hits + 1))
    [[ "$text" == *"@ s0 legend"* ]] && hits=$((hits + 1))
    [[ "$text" == *"@TYPE xy"* || "$text" == *"@TYPE XY"* ]] && hits=$((hits + 1))
    [[ "$text" == *"Generated by"* ]] && hits=$((hits + 1))
    [[ "$text" == *"Performance:"* ]] && hits=$((hits + 1))
    [[ "$text" == *"ns/day"* ]] && hits=$((hits + 1))
    [[ "$text" == *"Started mdrun"* ]] && hits=$((hits + 1))

    if [[ $hits -ge 3 ]]; then
        _STRATEGY_CONFIDENCE=95
        return 0
    fi
    if [[ $hits -ge 2 ]] && [[ "$text" == *"GROMACS"* || "$text" == *"gmx"* ]]; then
        _STRATEGY_CONFIDENCE=85
        return 0
    fi
    return 1
}

strategy_extract () {
    local text="$1"
    local result=""

    # Detect if this is xvg or log format
    local is_xvg=0
    local is_log=0
    [[ "$text" == *"@TYPE"* || "$text" == *"@ s0"* || "$text" == *"@    xaxis"* ]] && is_xvg=1
    [[ "$text" == *"Started mdrun"* || "$text" == *"Performance:"* || "$text" == *"Core t (s)"* ]] && is_log=1

    # Parse xvg format (Grace/xmgrace format)
    if [[ $is_xvg -eq 1 ]]; then
        result+="format xvg"$'\n'

        local num_legends=0
        local num_datapoints=0

        while IFS= read -r line; do
            # Title: @    title "Energy"
            if [[ "$line" =~ ^@\ +title\ +\"([^\"]+)\" ]]; then
                result+="title ${BASH_REMATCH[1]}"$'\n'
                continue
            fi

            # X axis label
            if [[ "$line" =~ ^@\ +xaxis\ +label\ +\"([^\"]+)\" ]]; then
                result+="xaxis_label ${BASH_REMATCH[1]}"$'\n'
                continue
            fi

            # Y axis label
            if [[ "$line" =~ ^@\ +yaxis\ +label\ +\"([^\"]+)\" ]]; then
                result+="yaxis_label ${BASH_REMATCH[1]}"$'\n'
                continue
            fi

            # Legends: @ s0 legend "Total Energy"
            if [[ "$line" =~ ^@\ +s([0-9]+)\ +legend\ +\"([^\"]+)\" ]]; then
                num_legends=$((num_legends + 1))
                local idx="${BASH_REMATCH[1]}"
                local legend="${BASH_REMATCH[2]}"
                result+="legend.s${idx} ${legend}"$'\n'
                continue
            fi

            # Data lines: numbers (not comments or directives)
            if [[ "$line" =~ ^[[:space:]]*[0-9] || "$line" =~ ^[[:space:]]*-[0-9] ]]; then
                num_datapoints=$((num_datapoints + 1))
                continue
            fi
        done <<< "$text"

        [[ $num_legends -gt 0 ]] && result+="num_legends ${num_legends}"$'\n'
        [[ $num_datapoints -gt 0 ]] && result+="num_datapoints ${num_datapoints}"$'\n'
    fi

    # Parse log format
    if [[ $is_log -eq 1 ]]; then
        result+="format log"$'\n'

        while IFS= read -r line; do
            local trimmed="$line"
            while [[ "$trimmed" == " "* ]]; do trimmed="${trimmed# }"; done

            # GROMACS version
            if [[ "$trimmed" =~ GROMACS\ +version:?\ *(.+) ]]; then
                local ver="${BASH_REMATCH[1]}"
                while [[ "$ver" == *" " ]]; do ver="${ver% }"; done
                result+="gromacs_version ${ver}"$'\n'
                continue
            fi

            # Performance line: "Performance:  12.345  ns/day"
            if [[ "$trimmed" =~ ^Performance:\ +([0-9.]+) ]]; then
                result+="performance_ns_per_day ${BASH_REMATCH[1]}"$'\n'
                continue
            fi

            # Wall time: "Time:   123.456   456.789"
            # Or: "               Core t (s)   Wall t (s)        (%)"
            #     "       Time:      123.456      45.678      271.0"
            if [[ "$trimmed" =~ ^Time:\ +([0-9.]+)\ +([0-9.]+) ]]; then
                result+="core_time ${BASH_REMATCH[1]}"$'\n'
                result+="wall_time ${BASH_REMATCH[2]}"$'\n'
                continue
            fi

            # Number of atoms
            if [[ "$trimmed" =~ ^System\ +([0-9]+)\ +atoms ]]; then
                result+="num_atoms ${BASH_REMATCH[1]}"$'\n'
                continue
            fi
            if [[ "$trimmed" == *"number of atoms"*"="* ]]; then
                if [[ "$trimmed" =~ =\ *([0-9]+) ]]; then
                    result+="num_atoms ${BASH_REMATCH[1]}"$'\n'
                fi
                continue
            fi

            # Number of steps
            if [[ "$trimmed" =~ nsteps\ *=\ *([0-9]+) ]]; then
                result+="nsteps ${BASH_REMATCH[1]}"$'\n'
                continue
            fi

            # dt
            if [[ "$trimmed" =~ ^dt\ *=\ *([0-9.]+) ]]; then
                result+="dt ${BASH_REMATCH[1]}"$'\n'
                continue
            fi

            # Simulation time
            if [[ "$trimmed" =~ ^[Ss]imulation\ +[Tt]ime:?\ *([0-9.]+) ]]; then
                result+="simulation_time ${BASH_REMATCH[1]}"$'\n'
                continue
            fi
        done <<< "$text"
    fi

    echo "$result"
}

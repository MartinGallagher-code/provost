################################################################################
## Line coverage, coverage hold and rescue (lib/_discovery.sh)
##
## Coverage = the share of the input's non-blank lines that reached the parse
## (_parse_coverage). --emit-meta carries it as a 4th field. When the first
## ranked candidate to produce output keeps under _FR_COV_MIN (60%) of the
## lines, it is HELD and the rescue parser (kv-report) runs; the rescue wins
## only when it covers _FR_COV_GAIN (25) points more. Fixtures are multi-
## section reports written for this test (not corpus / benchmark inputs):
## samples/kv-report/{mise-doctor,xdpyinfo,brew-config}.txt and
## samples/gnu-version/{sed,vaultctl}.txt.
################################################################################

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "$SCRIPT_DIR/helpers.sh"

echo ""
echo "========================================"
echo "Coverage Hold + Rescue Tests"
echo "========================================"

EXTRACT_DIR="$(dirname "$PROVOST_EXTRACT_SCRIPT")"
KVR="$EXTRACT_DIR/samples/kv-report"
GNV="$EXTRACT_DIR/samples/gnu-version"
TMPDIR_C="$(mktemp -d "${TMPDIR:-/tmp}/coverage_tests.XXXXXX")"

# _meta ARGS... — the --emit-meta line's fields 2-4 (strategy, conf, coverage)
_meta () {
    run_extract --emit-meta -f tsv --max-strategies 1 "$@" 2>&1 >/dev/null \
        | awk -F'\t' '/^__EXTRACT_META__/ { print $2 "\t" $3 "\t" $4 }'
}
_winner () { _meta "$@" | cut -f1; }
_cov () { _meta "$@" | cut -f3; }

test_meta_has_coverage () {
    local m; m="$(_meta "$KVR/brew-config.txt")"
    assert_match "$m" $'^colons\t[0-9]+\t100$' "meta: strategy, confidence, coverage 100"
}

test_meta_coverage_not_measured () {
    local m; m="$(_FR_COV_BYTES=0 _meta "$KVR/brew-config.txt")"
    assert_match "$m" $'^colons\t[0-9]+\t-$' "coverage above _FR_COV_BYTES is '-'"
}

test_pinned_reports_low_coverage () {
    # a pinned strategy is never held, but its coverage is still reported
    local c; c="$(_cov -s block-records "$KVR/mise-doctor.txt")"
    assert_match "$c" '^[0-9]+$' "pinned: coverage measured"
    [[ "$c" =~ ^[0-9]+$ && "$c" -lt 60 ]] || _assert_failed "block-records keeps < 60% of mise doctor (got $c)"
}

test_comment_lines_not_counted () {
    printf '# generated by test\n; also a comment\nalpha: 1\nbeta: 2\ngamma: 3\n' > "$TMPDIR_C/cm.txt"
    assert_eq "$(_cov -s colons "$TMPDIR_C/cm.txt")" "100" "comment lines are not counted"
}

test_rescue_mise_doctor () {
    local m; m="$(_meta "$KVR/mise-doctor.txt")"
    assert_match "$m" $'^kv-report\t70\t(9[0-9]|100)$' "mise doctor: held block-records parse rescued by kv-report"
    local out; out="$(run_extract -f plain --max-strategies 1 "$KVR/mise-doctor.txt" 2>/dev/null)"
    assert_contains "$out" "value terraform@1.7.4" "list items kept as rows (toolset)"
    assert_contains "$out" "section build_info" "nested kv carries its section"
    assert_contains "$out" "key config_files" "bare label over a list is the key"
}

test_rescue_generic_mode () {
    assert_eq "$(_winner --generic "$KVR/mise-doctor.txt")" "kv-report" "--generic: rescue applies"
    assert_eq "$(_winner --generic "$KVR/xdpyinfo.txt")" "kv-report" "--generic: xdpyinfo rescued"
}

test_rescue_xdpyinfo_rows () {
    local out; out="$(run_extract -f plain --max-strategies 1 "$KVR/xdpyinfo.txt" 2>/dev/null)"
    assert_contains "$out" "value XInputExtension" "extension list items are rows of their own"
    assert_contains "$out" "section screen #0" "screen block keeps its section"
    assert_contains "$out" "key options" "a key at the header's colon column stays in its section"
}

test_no_rescue_when_covered () {
    assert_eq "$(_winner "$KVR/brew-config.txt")" "colons" "a covering parse is never held"
}

test_hold_off_switches () {
    assert_eq "$(_FR_COV_MIN=0 _winner "$KVR/mise-doctor.txt")" "block-records" "_FR_COV_MIN=0: no hold"
    assert_eq "$(_FR_COV_BYTES=0 _winner "$KVR/mise-doctor.txt")" "block-records" "not measured: no hold"
    assert_eq "$(_winner --rank priority "$KVR/mise-doctor.txt")" "block-records" "--rank priority: no hold"
    assert_eq "$(_FR_COV_GAIN=101 _winner "$KVR/mise-doctor.txt")" "block-records" "rescue needs the gain"
}

test_hint_routed_is_exempt () {
    printf 'mise-doctor\tprefix\tversion: \tblock-records\n' > "$TMPDIR_C/hints.tsv"
    local w; w="$(PROVOST_HINTS_FILE="$TMPDIR_C/hints.tsv" _winner "$KVR/mise-doctor.txt")"
    assert_eq "$w" "mise-doctor" "a hint-routed claim is never held"
}

test_table_is_not_held () {
    # a table whose report also carries summary lines: the rows are the
    # dataset, the summary is another one (--multi) — kept, coverage reported
    printf 'Volume   Files   Size   Status\nvol-a    12      1.0    OK\nvol-b    13      2.0    OK\nvol-c    14      3.0    WARN\nvol-d    15      4.0    OK\nvol-e    16      5.0    OK\nvol-f    17      6.0    OK\n\nElapsed time:   01:00:12\nExit code:      0\nNext run:       2026-07-12 01:00\nOperator name:  ops team\nPool name:      main pool\nRetention:      7 days\n' > "$TMPDIR_C/table.txt"
    local m; m="$(_meta "$TMPDIR_C/table.txt")"
    assert_match "$m" $'^embedded-table\t80\t[0-5][0-9]$' "table claim kept with its (low) coverage"
    assert_contains "$(run_extract --explain "$TMPDIR_C/table.txt" 2>/dev/null)" "but its parse is a table" "explain says why"
}

test_bespoke_is_not_held () {
    # a bespoke (plugin) strategy that keeps the first 12 lines of a report
    # (enough fields to clear the truncation guard): its coverage is
    # reported, its claim is never second-guessed
    mkdir -p "$TMPDIR_C/plug"
    cat > "$TMPDIR_C/plug/head-lines.sh" <<'STRAT'
#!/bin/bash
## Name: head-lines
## Description: coverage test plugin — keeps the first 12 non-blank lines
## Version: 1.0
## Priority: 5

strategy_detect () { _STRATEGY_CONFIDENCE=92; [[ "$1" == version:* ]]; }
strategy_extract () { printf '%s\n' "$1" | awk 'NF && n < 12 { n++; print "l" n " " $0 }'; }
STRAT
    local m; m="$(_meta --plugin-dir "$TMPDIR_C/plug" "$KVR/mise-doctor.txt")"
    assert_match "$m" $'^head-lines\t92\t[1-5][0-9]$' "bespoke claim kept, low coverage visible"
}

test_pruning_exact () {
    local f a b
    for f in "$KVR/mise-doctor.txt" "$KVR/xdpyinfo.txt" "$KVR/brew-config.txt"; do
        a="$(run_extract --emit-meta -f tsv --max-strategies 1 "$f" 2>&1)"
        b="$(_EAS_NOPRUNE=1 run_extract --emit-meta -f tsv --max-strategies 1 "$f" 2>&1)"
        assert_eq "$b" "$a" "$(basename "$f"): unpruned == pruned"
    done
}

test_routes_identical () {
    # file lane + awk twins: the held claim moves to lane.held, the rescue
    # writes lane.result — bytes and meta must match the plain route
    local f a b c
    for f in "$KVR/mise-doctor.txt" "$KVR/brew-config.txt"; do
        a="$(run_extract --emit-meta -f tsv --max-strategies 1 "$f" 2>&1)"
        b="$(_FR_LANE_BYTES=0 run_extract --emit-meta -f tsv --max-strategies 1 "$f" 2>&1)"
        c="$(_FR_BIG_BYTES=0 run_extract --emit-meta -f tsv --max-strategies 1 "$f" 2>&1)"
        assert_eq "$b" "$a" "$(basename "$f"): file lane == plain"
        assert_eq "$c" "$a" "$(basename "$f"): awk twins == plain"
    done
    # a held claim that is NOT replaced is restored from the lane too
    a="$(_FR_COV_GAIN=101 run_extract --emit-meta -f tsv --max-strategies 1 "$KVR/mise-doctor.txt" 2>&1)"
    b="$(_FR_COV_GAIN=101 _FR_LANE_BYTES=0 run_extract --emit-meta -f tsv --max-strategies 1 "$KVR/mise-doctor.txt" 2>&1)"
    assert_eq "$b" "$a" "restored held claim: file lane == plain"
    c="$(_FR_COV_MIN=0 run_extract --emit-meta -f tsv --max-strategies 1 "$KVR/mise-doctor.txt" 2>&1)"
    assert_eq "${a%%__EXTRACT_META__*}" "${c%%__EXTRACT_META__*}" "restored held claim == never-held output"
}

test_rescue_only_never_ranks () {
    local ex; ex="$(run_extract --explain "$KVR/mise-doctor.txt" 2>/dev/null)"
    assert_not_contains "$(grep '^MATCH' <<< "$ex")" "kv-report" "kv-report is not a ranked candidate"
    assert_contains "$ex" "COV" "explain shows a coverage column"
    assert_contains "$ex" "kv-report: keeps" "explain previews the rescue"
    assert_contains "$ex" "REPLACES 'block-records'" "explain names the replaced claim"
}

test_gnu_version_keeps_rest () {
    local out m
    out="$(run_extract -f plain --max-strategies 1 "$GNV/vaultctl.txt" 2>/dev/null)"
    m="$(_meta "$GNV/vaultctl.txt")"
    assert_match "$m" $'^gnu-version\t92\t(8[0-9]|9[0-9]|100)$' "gnu-version keeps most of the report"
    assert_contains "$out" "libsodium 1.0.18" "component version line kept"
    assert_contains "$out" "kdf Argon2id, scrypt, PBKDF2-SHA256, HKDF-SHA256, HKDF-SHA512" "wrapped list folded"
    assert_contains "$out" "config /etc/vaultctl/vaultctl.conf" "label lines kept"
    out="$(run_extract -f plain --max-strategies 1 "$GNV/sed.txt" 2>/dev/null)"
    assert_contains "$out" "e_mail_bug_reports_to bug-sed@gnu.org" "<url> value unwrapped"
    assert_contains "$out" "notes This sed program was built with SELinux support." "unlabelled lines kept in notes"
    assert_contains "$out" "author Jay Fenlason" "author still parsed"
}

run_test "meta carries coverage"                    test_meta_has_coverage
run_test "coverage not measured above the cap"      test_meta_coverage_not_measured
run_test "pinned strategy reports low coverage"     test_pinned_reports_low_coverage
run_test "comment lines are not counted"            test_comment_lines_not_counted
run_test "rescue: mise doctor"                      test_rescue_mise_doctor
run_test "rescue: --generic"                        test_rescue_generic_mode
run_test "rescue: xdpyinfo rows"                    test_rescue_xdpyinfo_rows
run_test "no rescue for a covering parse"           test_no_rescue_when_covered
run_test "hold switches"                            test_hold_off_switches
run_test "hint-routed claims are exempt"            test_hint_routed_is_exempt
run_test "a table claim is not held"               test_table_is_not_held
run_test "a bespoke claim is not held"              test_bespoke_is_not_held
run_test "pruning stays exact"                      test_pruning_exact
run_test "file lane / awk twin routes identical"    test_routes_identical
run_test "kv-report is rescue-only"                 test_rescue_only_never_ranks
run_test "gnu-version keeps the rest of the report" test_gnu_version_keeps_rest

rm -rf "$TMPDIR_C"
print_summary

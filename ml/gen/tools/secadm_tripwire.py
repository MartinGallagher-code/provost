"""Open Source Tripwire `tripwire --check` integrity report: banner, padded
`Key:  value` header blocks, `====` / `----` framed section titles, a rule
summary table (with a `*` flag column for rules with violations), totals,
per-object detail, error report and the copyright footer."""
from lib import Doc, fake

TOOL = "tripwire"

RULES = [("Invariant Directories", 66), ("Temporary directories", 33), ("Other binaries", 66),
         ("Tripwire Binaries", 100), ("Other libraries", 66), ("Root file-system executables", 100),
         ("System boot changes", 100), ("Tripwire Data Files", 100), ("Critical configuration files", 100),
         ("Critical system boot files", 100), ("Security Control", 66), ("Root file-system libraries", 100),
         ("Shell Binaries", 100), ("File System and Disk Administraton Programs", 100),
         ("Kernel Administration Programs", 100), ("Networking Programs", 100),
         ("System Administration Programs", 100), ("Hardware and Device Control Programs", 100),
         ("System Information Programs", 100), ("Application Information Programs", 100),
         ("Shell Related Programs", 100), ("Critical Utility Sym-Links", 100), ("Root config files", 100),
         ("Devices & Kernel information", 100), ("OS executables and libraries", 100),
         ("Monitor Filesystems", 33), ("User binaries", 66), ("Libraries", 66)]
FILES = {"Critical configuration files": ["/etc/passwd", "/etc/shadow", "/etc/group", "/etc/hosts", "/etc/sudoers"],
         "Root config files": ["/root", "/root/.bash_history", "/root/.viminfo"],
         "Devices & Kernel information": ["/dev", "/proc/kcore"],
         "System boot changes": ["/var/run/utmp", "/var/log/wtmp", "/dev/log"],
         "Other binaries": ["/usr/local/bin/backup.sh", "/usr/sbin/sshd", "/usr/bin/sudo"],
         "Monitor Filesystems": ["/var/log/secure", "/var/log/messages"]}
RULE = "=" * 79
DASH = "-" * 79


def banner(d, title):
    d.skip(RULE)
    d.section(title + ":", title)
    d.skip(RULE)
    d.blank()


def pad(d, k, v, w=30):
    d.line((k + ":").ljust(w) + v, "kv", [k, v])


def generate(rng):
    d = Doc()
    ver = rng.choice(["2.4.3.7", "2.4.2.2", "2.4.3.1", "2.4.1.2"])
    host = fake.host(rng).split(".")[0]
    d.skip(f"Open Source Tripwire(R) {ver} Integrity Check Report")
    d.blank()
    day = rng.choice(["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"])
    mon = rng.choice("Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split())
    H, M, S = rng.randint(0, 23), rng.randint(0, 59), rng.randint(0, 59)
    created = rng.choice([f"{day} {mon} {rng.randint(1, 28):2d} {H:02d}:{M:02d}:{S:02d} {rng.choice([2025, 2026])}",
                          f"{day} {rng.randint(1, 28):02d} {mon} {rng.choice([2025, 2026])} {H % 12 or 12:02d}:{M:02d}:{S:02d} {'AM' if H < 12 else 'PM'} UTC"])
    pad(d, "Report generated by", rng.choice(["root", "root", "tripwire"]))
    pad(d, "Report created on", created)
    pad(d, "Database last updated on", rng.choice(["Never", created[:-4] + "UTC" if created.endswith("UTC") else created]))
    d.blank()
    banner(d, "Report Summary")
    pad(d, "Host name", host)
    pad(d, "Host IP address", rng.choice([fake.ip(rng), "Unknown IP", "127.0.1.1"]))
    pad(d, "Host ID", rng.choice(["None", fake.hexid(rng, 8)]))
    pad(d, "Policy file used", "/etc/tripwire/tw.pol")
    pad(d, "Configuration file used", "/etc/tripwire/tw.cfg")
    pad(d, "Database file used", f"/var/lib/tripwire/{host}.twd")
    pad(d, "Command line used", rng.choice(["tripwire --check", "/usr/sbin/tripwire --check",
                                            "tripwire -m c", "tripwire --check --interactive"]))
    d.blank()
    banner(d, "Rule Summary")
    d.skip(DASH)
    d.line("  Section: Unix File System", "section", ["Unix File System"])
    d.skip(DASH)
    d.blank()
    rules = rng.sample(RULES, rng.randint(5, 20))
    rows, viol = [], []
    for name, sev in rules:
        a = r = m = 0
        if rng.random() < .2:
            a, r, m = rng.choice([0, 0, 1, 2]), rng.choice([0, 0, 1]), rng.randint(0, 6)
            if a + r + m == 0:
                m = 1
            viol.append((name, sev, a, r, m))
        rows.append(["*" if a + r + m else None, name, str(sev), str(a), str(r), str(m)])
    nw = max(31, max(len(x[1]) for x in rows) + 1)

    def line(flag, name, sev, a, r, m):
        return f"{flag or ' '} {name.ljust(nw)} {sev.ljust(17)} {a.ljust(8)} {r.ljust(8)} {m}"

    d.line(line(None, "Rule Name", "Severity Level", "Added", "Removed", "Modified"), "header",
           [None, "Rule Name", "Severity Level", "Added", "Removed", "Modified"])
    d.skip(line(None, "---------", "--------------", "-----", "-------", "--------"))
    for x in rows:
        d.line(line(*x), "row", x)
    d.blank()
    total_v = sum(a + r + m for _, _, a, r, m in viol)
    n = str(rng.randint(8000, 160000))
    d.line(f"Total objects scanned:  {n}", "kv", ["Total objects scanned", n])
    d.line(f"Total violations found:  {total_v}", "kv", ["Total violations found", str(total_v)])
    d.blank()
    if viol:
        banner(d, "Object Summary")
        d.skip(DASH)
        d.line("# Section: Unix File System", "section", ["Unix File System"])
        d.skip(DASH)
        d.blank()
        for name, sev, a, r, m in viol:
            d.skip(DASH)
            d.line(f"Rule Name: {name}", "kv", ["Rule Name", name])
            d.line(f"Severity Level: {sev}", "kv", ["Severity Level", str(sev)])
            d.skip(DASH)
            pool = FILES.get(name, ["/etc/" + fake.word(rng) + ".conf", fake.path(rng), fake.path(rng)])
            for label, cnt in (("Added", a), ("Removed", r), ("Modified", m)):
                if not cnt:
                    continue
                d.blank()
                d.section(f"{label}:", label)
                for _ in range(cnt):
                    p = rng.choice(pool + [fake.path(rng)])
                    d.line(f'"{p}"', "row", [f'"{p}"'])
            d.blank()
    banner(d, "Error Report")
    if rng.random() < .75:
        d.skip("No Errors")
    else:
        d.skip(DASH)
        d.line("   Section: Unix File System", "section", ["Unix File System"])
        d.skip(DASH)
        d.blank()
        for i in range(1, rng.randint(2, 5)):
            p = rng.choice(["/proc/scsi", "/root/.esd_auth", "/sbin/fsck.reiserfs", "/usr/sbin/fixrmtab",
                            "/root/mail", "/etc/rc.boot", "/var/lock/subsys", fake.path(rng)])
            d.line(f"{i}.  File system error.", "row", [f"{i}.", "File system error."])
            d.line(f"     Filename: {p}", "kv", ["Filename", p])
            d.line("     No such file or directory", "skip")
            d.blank()
    d.blank()
    d.skip(DASH)
    d.skip("*** End of report ***")
    d.blank()
    d.skip("Open Source Tripwire 2.4 Portions copyright 2000-2018 Tripwire, Inc. Tripwire is a registered")
    d.skip("trademark of Tripwire, Inc. This software comes with ABSOLUTELY NO WARRANTY;")
    d.skip("for details use --version. This is free software which may be redistributed")
    d.skip("or modified only under certain conditions; see COPYING for details.")
    d.skip("All rights reserved.")
    return d

"""Windows `scoop list`: an "Installed apps:" heading, then a PowerShell
Format-Table (dashes as long as each header name, one space between columns)
with an optional Info column."""
import re
from lib import Doc

TOOL = "scoop-list"

APPS = ["7zip", "git", "python", "nodejs-lts", "neovim", "ripgrep", "fd", "fzf", "bat", "jq", "curl",
        "gsudo", "starship", "vscode", "windows-terminal", "everything", "sumatrapdf", "go", "rustup",
        "llvm", "cmake", "ninja", "aria2", "dark", "innounp", "lessmsi", "openssh", "pwsh", "sysinternals",
        "firacode-nf", "JetBrainsMono-NF", "nvm", "temurin17-jdk", "obsidian", "keepassxc", "ffmpeg"]
BUCKETS = ["main", "main", "main", "extras", "extras", "versions", "nerd-fonts", "java", "nonportable"]
INFO = ["Global install", "Held package", "Install failed", "Deprecated package", "Global install, Held package"]


def version(rng, app):
    if app == "git":
        return f"2.{rng.randint(30, 45)}.{rng.randint(0, 3)}.windows.{rng.randint(1, 3)}"
    if rng.random() < .1:
        return f"{rng.randint(2019, 2026)}{rng.randint(1, 12):02d}{rng.randint(1, 28):02d}"
    if rng.random() < .1:
        return "nightly-" + str(rng.randint(20230101, 20261231))
    return ".".join(str(rng.randint(0, 40)) for _ in range(rng.randint(2, 4)))


def generate(rng):
    d = Doc()
    if rng.random() < .4:
        d.blank()
    d.section("Installed apps:")
    d.blank()
    apps = sorted(rng.sample(APPS, rng.randint(2, 18)), key=str.lower)
    with_info = rng.random() < .7
    rows = []
    for a in apps:
        src = rng.choice(BUCKETS)
        if rng.random() < .05:
            src = rng.choice([r"C:\Users\me\manifests\%s.json" % a, "<auto-generated>"])
        upd = f"{rng.randint(2021, 2026)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d} " \
              f"{rng.randint(0, 23):02d}:{rng.randint(0, 59):02d}:{rng.randint(0, 59):02d}"
        row = [a, version(rng, a), src, upd]
        if with_info:
            row.append(rng.choice(INFO) if rng.random() < .2 else None)
        rows.append(row)
    hdr = ["Name", "Version", "Source", "Updated"] + (["Info"] if with_info else [])
    d.table(hdr, rows, gap=1, rule="-")
    i = len(d.lines) - len(rows) - 1
    d.lines[i] = re.sub(r"\S", "-", d.lines[i - 1])
    if rng.random() < .5:
        d.blank()
    return d
